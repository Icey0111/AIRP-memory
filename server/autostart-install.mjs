// 一键安装/卸载「开机自启」(Windows): 把记忆服务注册到登录启动项, 隐藏窗口后台运行
//
// 用法:
//   node autostart-install.mjs              安装 (服务用"当前这个 node"运行, 路径随之固化)
//   node autostart-install.mjs --remove     卸载
//
// 原理: 往当前用户的「启动」文件夹写一个 .vbs (UTF-16LE, 兼容中文路径),
//       登录时由 WScript 以**隐藏窗口**(运行样式 0)启动 node src/index.js。
//       面板侧有 10 秒离线自动探测, 服务上线即自动连接, 用户全程无感。
//
// 注意: 服务绑定 127.0.0.1 时不需令牌; 若 config.json 已改绑 0.0.0.0,
//       请务必先设 server.token 再装自启 (局域网暴露面由令牌兜底)。
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';

const SERVER_DIR = path.dirname(fileURLToPath(import.meta.url));   // 本脚本就在 server/ 里
// 登录自启指向**看门狗**而非服务本体: 打开 TauriTavern 时服务才跟着启动 (用户要求的语义)
const SERVICE_ENTRY = path.join(SERVER_DIR, 'watch-tavern.mjs');
const VBS_NAME = 'tavern-memory-autostart.vbs';

function startupDir() {
  const appData = process.env.APPDATA
    ?? path.join(os.homedir(), 'AppData', 'Roaming');
  return path.join(appData, 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup');
}

function vbsPath() {
  return path.join(startupDir(), VBS_NAME);
}

function buildVbs() {
  const nodeExe = process.execPath;               // 用运行本安装器的 node (含 TauriTavern 自带的)
  const q = (s) => `"${s}"`;
  // WScript.Shell.Run 的窗口样式 0 = 隐藏; 第三个参数 False = 不等待
  return [
    `' TavernMemory autostart (generated by server/autostart-install.mjs; safe to delete)`,
    `Set sh = CreateObject("WScript.Shell")`,
    `sh.CurrentDirectory = ${q(SERVER_DIR)}`,
    `sh.Run """${nodeExe}"" ""${SERVICE_ENTRY}""", 0, False`,
    '',
  ].join('\r\n');
}

function install() {
  if (process.platform !== 'win32') {
    console.error('本脚本仅支持 Windows (启动项方式)。Linux/macOS 请用 systemd / launchd 托管 server/src/index.js。');
    process.exit(1);
  }
  if (!fs.existsSync(SERVICE_ENTRY)) {
    console.error(`[X] 找不到服务入口: ${SERVICE_ENTRY}`);
    process.exit(1);
  }
  fs.mkdirSync(startupDir(), { recursive: true });
  // UTF-16LE + BOM: WScript 才能正确解析含中文的路径
  fs.writeFileSync(vbsPath(), `\ufeff${buildVbs()}`, { encoding: 'utf16le' });
  console.log('[OK] 已安装开机自启 (登录后隐藏运行, 无窗口):');
  console.log(`     启动项: ${vbsPath()}`);
  console.log(`     服务:   ${process.execPath} ${SERVICE_ENTRY}`);
  console.log('     立即体验可重启一次电脑, 或本机手动启动一次; 面板会自动连上。');
  console.log('     卸载: node autostart-install.mjs --remove');
}

function remove() {
  const p = vbsPath();
  if (fs.existsSync(p)) {
    fs.rmSync(p);
    console.log(`[OK] 已移除开机自启: ${p}`);
  } else {
    console.log('未发现已安装的自启项 (本来就未安装)。');
  }
}

const isRemove = process.argv.includes('--remove') || process.argv.includes('-r');
isRemove ? remove() : install();

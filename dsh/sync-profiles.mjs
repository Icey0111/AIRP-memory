// 把 AIRP 预设同步进各 dsh profile —— 仓库是唯一真源，profile 里的那一块是生成物。
//
//   node dsh/sync-profiles.mjs            同步（覆盖生成块，备份旧文件为 .bak）
//   node dsh/sync-profiles.mjs --dry-run  只打印将要发生的事，不写盘
//
// 目标：
//   ~/.dsh/profiles/airp/cordis.patch.yml     AIRP 专属 Web profile（默认预设即 airp-roleplay）
//   ~/.dsh/profiles/desktop/cordis.patch.yml  桌面端（只追加预设，保留 App 自己写的条目；
//                                             默认预设不动 —— 原版行为与今天完全一致）
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.dirname(HERE);
const DSH_HOME = process.env.DSH_HOME ?? path.join(os.homedir(), '.dsh');
const PRESET_SRC = path.join(HERE, 'airp-preset.patch.yml');

const BEGIN = '# >>> AIRP-PRESET (generated by dsh/sync-profiles.mjs — edit dsh/airp-preset.patch.yml instead) >>>';
const END = '# <<< AIRP-PRESET <<<';
const DISCIPLINE_SRC = path.join(REPO, 'AIRP.md');
const DISCIPLINE_TOKEN = '@@AIRP_DISCIPLINE@@';

const dryRun = process.argv.includes('--dry-run');

/**
 * 纪律文本: AIRP.md 是唯一真源, 整份内联进预设的 persona suffix (= system prompt 的常驻部分)。
 *
 * 为什么必须内联而不能只靠工作区里的文件: agent-instructions 只在**工作区根**找 AIRP.md,
 * 而用户实际在别的工作区玩 (实测: D:\临时 / E:\色彩)。那些会话里纪律文件不存在,
 * 模型就退回"凭自觉" —— 实测表现是三轮只织一次、chatId 用 default、characterId 不传。
 * 内联进 persona 与工作区无关, 一定在场。
 */
function disciplineText() {
  const raw = fs.readFileSync(DISCIPLINE_SRC, 'utf8');
  // 去掉标题行与顶部那段 HTML 注释 (那是给维护者看的, 不进 prompt)
  const body = raw
    .replace(/^#\s.*\n/, '')
    .replace(/<!--[\s\S]*?-->/, '')
    .trim();
  // RP 输出要求在前, 纪律在后 (先定调, 再给硬规则)
  return '以角色口吻输出正文。不要复述记忆条目本身，不要提及记忆系统、工具、注入等字样，'
    + '也不要解释你是如何想起这些事的。\n\n'
    + '==================== 记忆纪律 ====================\n'
    + body;
}

/** 取出预设本体：丢掉文件头部的注释块，保留 YAML 条目 */
function presetBody() {
  const raw = fs.readFileSync(PRESET_SRC, 'utf8').split(/\r?\n/);
  const firstEntry = raw.findIndex((l) => !l.trim().startsWith('#') && l.trim() !== '');
  if (firstEntry < 0) throw new Error('airp-preset.patch.yml 里没有 YAML 条目');
  let body = raw.slice(firstEntry).join('\n').replace(/\s*$/, '') + '\n';
  if (!body.includes(DISCIPLINE_TOKEN)) {
    throw new Error(`airp-preset.patch.yml 里缺少 ${DISCIPLINE_TOKEN} 占位符 (纪律会静默丢失)`);
  }
  // JSON 字符串是合法的 YAML 双引号标量 —— 用它承载多行纪律, 免去 YAML 缩进与转义的坑
  body = body.replace(`"${DISCIPLINE_TOKEN}"`, JSON.stringify(disciplineText()));
  return body;
}

/** AIRP 专属 profile 的头部：去 harness 化 + 权限 + 默认预设 */
function airpHeader() {
  return `# AIRP 模式的 dsh profile 补丁 —— 本文件由 dsh/sync-profiles.mjs 生成，不要手改。
# 真源: dsh/airp-preset.patch.yml (预设) + 本文件头部 (AIRP 模式专属开关)
# 原版(profile=desktop / web)不读这个文件, 这里的改动不会外溢。

# 去 harness 化: 不自我介绍、不塞工作目录/平台信息(沉浸 + 省 token)
- id: system-prompt
  config:
    includeHarnessIdentity: false
    includeRuntimeContext: false

# 权限: 角色扮演不能每步弹审批。config 整体替换, 故把出厂三个预设一并带上。
- id: permission
  config:
    presets:
      airp:
        name: AIRP 角色扮演
        description: 工作区内读写, 不弹审批(记忆库写入只经 MCP 工具)
        sandbox: workspace-write
        approval: never
      read-only:
        sandbox: read-only
        approval: ask
      workspace-write:
        sandbox: workspace-write
        approval: ask
      danger-full-access:
        sandbox: danger-full-access
        approval: never
    defaultPreset: airp

# 本 profile 开局即角色扮演预设
- id: agent-preset-registry
  config:
    default: airp-roleplay
`;
}

/** 桌面端只追加两块: 预设本体 + 多一个权限预设(默认权限预设不动) */
function desktopHeader() {
  return `# 桌面端补充块 —— 由 dsh/sync-profiles.mjs 生成。
# 1) 权限: 只为 AIRP 会话加一个"不弹审批"的选项, 默认权限预设保持出厂值不变;
#    用 AIRP 预设开新会话时, 在 UI 把权限切到「AIRP 角色扮演」即可。
- id: permission
  config:
    presets:
      airp:
        name: AIRP 角色扮演
        description: 工作区内读写, 不弹审批(记忆库写入只经 MCP 工具)
        sandbox: workspace-write
        approval: never
      read-only:
        sandbox: read-only
        approval: ask
      workspace-write:
        sandbox: workspace-write
        approval: ask
      danger-full-access:
        sandbox: danger-full-access
        approval: never
`;
}

/** 去掉已有的生成块，保留 profile 自己的条目 */
function stripBlock(text) {
  const start = text.indexOf(BEGIN);
  if (start < 0) return text.replace(/\s*$/, '\n');
  const endIdx = text.indexOf(END, start);
  const after = endIdx < 0 ? '' : text.slice(endIdx + END.length);
  return (text.slice(0, start).replace(/\s*$/, '\n') + after.replace(/^\s*\n/, '')).replace(/\s*$/, '\n');
}

function writeTarget(file, header, body, { fresh = false } = {}) {
  const block = `${BEGIN}\n${header}\n${body}${END}\n`;
  const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  const kept = fresh ? '' : stripBlock(existing ?? '');
  const next = `${kept}${kept ? '\n' : ''}${block}`;

  const label = path.relative(DSH_HOME, file);
  if (existing === next) {
    console.log(`= ${label} 已是最新`);
    return;
  }
  if (dryRun) {
    console.log(`~ ${label} 将写入 ${next.length} 字符`);
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (existing !== null) fs.writeFileSync(`${file}.bak`, existing);
  fs.writeFileSync(file, next);
  console.log(`+ ${label} 已更新${existing !== null ? ' (旧文件备份为 .bak)' : ''}`);
}

const body = presetBody();

// AIRP 专属 profile: 整份文件都是生成物
writeTarget(path.join(DSH_HOME, 'profiles', 'airp', 'cordis.patch.yml'), airpHeader(), body, { fresh: true });

// 桌面端: 保留 App 自己写的条目, 只追加/更新生成块
writeTarget(path.join(DSH_HOME, 'profiles', 'desktop', 'cordis.patch.yml'), desktopHeader(), body);

console.log(dryRun ? '\n(dry-run: 未写盘)' : `\n同步完成。仓库真源: ${path.relative(REPO, PRESET_SRC)}`);
